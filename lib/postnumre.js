/**
 * Slår et postnummer op. Returnerer null for ukendte — aldrig et gæt.
 * @returns {{by:string, region_key:string}|null}
 */
export function slaaPostnrOp(postnr) {
  const n = String(postnr || "").trim();
  if (!/^\d{4}$/.test(n)) return null;
  const v = DATA[n];
  if (!v) return null;
  const i = v.lastIndexOf("|");
  return { by: v.slice(0, i), region_key: LANDSDEL[v.slice(i + 1)] || null };
}
